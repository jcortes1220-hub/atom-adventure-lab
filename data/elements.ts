export const elements = source.Table.Row.map((row) => {
  const e = Object.fromEntries(
    source.Table.Columns.Column.map((c, i) => [c, row.Cell[i]]),
  );
  const z = Number(e.AtomicNumber);
  const r = reference.elements.find((x) => x.number === z)!;
  const position = tableRows
    .flatMap((row, y) =>
      row.split(' ').map((s, x) => ({ s, x: x + 1, y: y + 1 })),
    )
    .find((p) => p.s === e.Symbol)!;
  const mass = isotopeMasses[z - 1] ?? null;
  return {
    symbol: e.Symbol,
    name: e.Name,
    number: z,
    mass: e.AtomicMass,
    category: e.GroupBlock,
    phase: e.StandardState || 'Unknown',
    configuration: e.ElectronConfiguration,
    shells: r.shells,
    period: r.period,
    group: (z >= 57 && z <= 71) || (z >= 89 && z <= 103) ? null : r.group,
    melting: e.MeltingPoint ? Number(e.MeltingPoint) : null,
    boiling: e.BoilingPoint ? Number(e.BoilingPoint) : null,
    density: e.Density || null,
    year: e.YearDiscovered,
    discoverer: r.discovered_by || 'Not recorded',
    nameOrigin: r.name
      ? 'See the element history reference for the origin of ' + r.name + '.'
      : 'Not recorded',
    history: r.summary,
    source: r.source,
    position,
    neutrons: mass === null ? null : mass - z,
    isotope: mass,
    description:
      notes[e.Symbol] ||
      e.Name +
        ' is a radioactive element made and studied by scientists. It has no everyday uses.',
    uses: [
      notes[e.Symbol] || 'Scientific research in specialist laboratories.',
    ],
    funFact:
      e.Symbol === 'Na'
        ? 'Sodium has one electron in its outer shell.'
        : e.Symbol === 'Cl'
          ? 'A chlorine atom can gain one electron to become a chloride ion.'
          : e.Symbol === 'C'
            ? 'Diamond and graphite contain the same element with different atom arrangements.'
            : e.Symbol === 'He'
              ? 'Helium was found in sunlight before it was found on Earth.'
              : e.Symbol === 'Ga'
                ? 'Gallium melts just above a warm room temperature.'
                : e.Symbol === 'W'
                  ? 'Tungsten has the highest melting point of all metals.'
                  : e.Name +
                    ' atoms always have ' +
                    z +
                    ' protons. Changing the proton count changes the element.',
    hazardous:
      z >= 84 ||
      [
        'Be',
        'F',
        'Na',
        'P',
        'Cl',
        'K',
        'As',
        'Br',
        'Rb',
        'Cd',
        'Cs',
        'Hg',
        'Tl',
        'Pb',
      ].includes(e.Symbol),
  };
});
export type Element = (typeof elements)[number];
export const bySymbol = Object.fromEntries(elements.map((e) => [e.symbol, e]));
export const categoryClass = (c: string) =>
  'cat-' + c.toLowerCase().replaceAll(' ', '-');
